#!/usr/bin/env python3
"""Generates GarminKit/Sources/GarminFIT/GarminExerciseCatalog.generated.swift from a Gadgetbridge checkout.

Usage:
    python3 scripts/generate_exercise_catalog.py /path/to/Gadgetbridge [-o OUTPUT]

Input, relative to the Gadgetbridge root:
    app/src/main/assets/workouts/exercises/garmin.json   the Garmin exercise catalog

Each exercise becomes one line of `id|name|category|code|strength`: the catalog id, the display name, the FIT
exercise_category number (from Gadgetbridge's ExerciseCategory enum), the exercise_name code or empty for the
category's generic exercise, and 1 when the exercise is in the strength list.

Only the Python standard library is used. The output is deterministic.
"""

import argparse
import json
import sys
from pathlib import Path

CATALOG_JSON = "app/src/main/assets/workouts/exercises/garmin.json"
FIT_PROFILE_JSON = "FitCodeGenerator/src/main/resources/fit_profile.json"
DEFAULT_OUTPUT = Path(__file__).resolve().parent.parent / "GarminKit/Sources/GarminFIT/GarminExerciseCatalog.generated.swift"


def category_numbers(root: Path) -> dict:
    profile = json.loads((root / FIT_PROFILE_JSON).read_text(encoding="utf-8"))
    for enum in profile["enumerations"]:
        if enum["name"] == "ExerciseCategory":
            return {entry["name"]: entry["num"] for entry in enum["entries"]}
    raise SystemExit("ExerciseCategory is missing from fit_profile.json")


def rows(root: Path) -> list:
    numbers = category_numbers(root)
    catalog = json.loads((root / CATALOG_JSON).read_text(encoding="utf-8"))
    lines = []
    for exercise in catalog["exercises"]:
        category = numbers[exercise["category"]]
        code = exercise.get("code")
        strength = 1 if "strength" in (exercise.get("lists") or []) else 0
        fields = [exercise["id"], exercise["name"], str(category), "" if code is None else str(code), str(strength)]
        for field in fields:
            if "|" in field or "\n" in field or '"""' in field or "\\" in field:
                raise SystemExit(f"Unsupported character in exercise {exercise['id']}")
        lines.append("|".join(fields))
    return lines


def render(lines: list) -> str:
    body = "\n".join(lines)
    return f'''// Generated by scripts/generate_exercise_catalog.py from Gadgetbridge's Garmin exercise catalog.
// Do not edit by hand; rerun the script.

enum GarminExerciseCatalogData {{
    /// One exercise per line: id|name|category|code|strength. See the script for the columns.
    static let rows = #"""
{body}
"""#
}}
'''


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("gadgetbridge", type=Path, help="Gadgetbridge checkout")
    parser.add_argument("-o", "--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    args.output.write_text(render(rows(args.gadgetbridge)), encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
