/// Kind of Garmin device, from the Gadgetbridge directory the coordinator lives in.
public enum GarminDeviceFamily: String, Sendable, CaseIterable {
    case watch, bikeComputer, heartRateMonitor, gpsHandheld
}

/// Capabilities Gadgetbridge declares for a model. Checks that depend on the device's state or on app
/// preferences in Gadgetbridge are not evaluated, so those features are absent here.
public enum GarminDeviceFeature: String, Sendable, CaseIterable {
    case heartRate, restingHeartRate, manualHeartRate, realtimeData, spo2, respiratoryRate, hrv, stress
    case bodyBattery, ecg, sleep, remSleep, awakeSleep, sleepScore, intensityMinutes, activeCalories
    case vo2Max, racePrediction, trainingStatus, trainingLoad, recordedActivities, dataFetching, weather
    case calendarEvents, solarCharging, findDevice, music, appNotifications, callControl, smsReply, sendWaypoint
}

/// One Garmin device model that Gadgetbridge supports. Generated by `scripts/generate_device_catalog.py`.
public struct GarminDeviceModel: Sendable, Hashable, Identifiable {
    /// Gadgetbridge string key without its prefix, e.g. "garmin_venu_4".
    public let id: String
    /// Gadgetbridge's name for the model, e.g. "Garmin Venu 4".
    public let displayName: String
    public let family: GarminDeviceFamily
    /// Java regex from the coordinator, converted to Swift Regex syntax. Matches the whole Bluetooth name.
    public let bluetoothNamePattern: String
    /// FIT product numbers (manufacturer 1) that identify this model. Empty when Gadgetbridge's FIT table has none.
    public let productNumbers: [Int]
    public let features: Set<GarminDeviceFeature>
    /// Alarm slots when the coordinator fixes them. Nil means the base class decides from the device's capabilities.
    public let alarmSlotCount: Int?
    /// Gadgetbridge turns on its new sync protocol for this model by default.
    public let usesNewSyncProtocol: Bool
    /// Gadgetbridge marks this model experimental (untested or unconfirmed name).
    public let isExperimental: Bool
    /// Coordinator class in Gadgetbridge this model was generated from.
    public let gadgetbridgeCoordinator: String
}
