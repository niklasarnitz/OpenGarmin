export const isGerman = (typeof navigator !== "undefined" ? navigator.language : "en").toLowerCase().startsWith("de");
export const locale = isGerman ? "de-DE" : "en-US";
export const lang: "en" | "de" = isGerman ? "de" : "en";

/** The string for a key, with {name} placeholders filled from vars. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = (isGerman ? de : en)[key];
  return text.replace(/\{(\w+)\}/g, (_, name: string) => String(vars[name] ?? `{${name}}`));
}

const SPORT_IDS = [0, 1, 2, 4, 5, 10, 11, 15, 17];

/** The name key for a FIT sport number; unknown sports read as a generic activity. */
export const sportKey = (n: number): Key => (SPORT_IDS.includes(n) ? (`sport_${n}` as Key) : "sport_0");
